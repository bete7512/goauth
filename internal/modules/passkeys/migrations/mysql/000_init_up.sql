CREATE TABLE IF NOT EXISTS passkey_credentials (
    id                 VARCHAR(36) PRIMARY KEY,
    user_id            VARCHAR(36) NOT NULL,
    credential_id      VARBINARY(512) NOT NULL,
    public_key         BLOB NOT NULL,
    attestation_type   VARCHAR(64) NOT NULL DEFAULT '',
    attestation_format VARCHAR(64) NOT NULL DEFAULT '',
    aaguid             VARBINARY(64),
    sign_count         BIGINT NOT NULL DEFAULT 0,
    transports         TEXT NOT NULL,
    backup_eligible    BOOLEAN NOT NULL DEFAULT FALSE,
    backup_state       BOOLEAN NOT NULL DEFAULT FALSE,
    user_present       BOOLEAN NOT NULL DEFAULT FALSE,
    user_verified      BOOLEAN NOT NULL DEFAULT FALSE,
    name               VARCHAR(255) NOT NULL DEFAULT '',
    last_used_at       DATETIME,
    created_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY idx_passkey_credentials_credential_id (credential_id),
    KEY idx_passkey_credentials_user_id (user_id)
);
