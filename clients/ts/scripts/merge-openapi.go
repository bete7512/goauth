// Command merge-openapi walks internal/modules/*/docs/openapi.yml, combines
// paths + components into a single specification, and writes the result to
// clients/ts/openapi.yml — which @hey-api/openapi-ts consumes to emit the
// TypeScript client.
//
// Run via: make sdk
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"github.com/bete7512/goauth/internal/docs/openapi"
	"gopkg.in/yaml.v3"
)

const (
	modulesGlob = "internal/modules/*/docs/openapi.yml"
	outputPath  = "clients/ts/openapi.yml"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "merge-openapi:", err)
		os.Exit(1)
	}
}

func run() error {
	matches, err := filepath.Glob(modulesGlob)
	if err != nil {
		return fmt.Errorf("glob: %w", err)
	}
	sort.Strings(matches)
	if len(matches) == 0 {
		return fmt.Errorf("no module openapi.yml files found — run from repo root")
	}

	merged := baseSpec()
	paths := merged["paths"].(map[string]any)
	components := merged["components"].(map[string]any)
	tagsByName := map[string]map[string]any{}

	strategy := os.Getenv("GOAUTH_SDK_STRATEGY")
	if strategy == "" {
		strategy = "stateless"
	}
	if strategy != "stateless" && strategy != "session" {
		return fmt.Errorf("GOAUTH_SDK_STRATEGY must be session or stateless")
	}
	for _, path := range matches {
		if (strings.Contains(path, "/session/") && strategy != "session") || (strings.Contains(path, "/stateless/") && strategy != "stateless") {
			continue
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read %s: %w", path, err)
		}
		var spec map[string]any
		if err := yaml.Unmarshal(raw, &spec); err != nil {
			return fmt.Errorf("parse %s: %w", path, err)
		}

		openapi.NamespaceComponents(filepath.Base(filepath.Dir(filepath.Dir(path))), spec)
		if p, ok := spec["paths"].(map[string]any); ok {
			for k, v := range p {
				if _, exists := paths[k]; exists {
					return fmt.Errorf("conflicting OpenAPI path %s in %s", k, path)
				}
				paths[k] = v
			}
		}
		if c, ok := spec["components"].(map[string]any); ok {
			if err := mergeComponents(components, c); err != nil {
				return fmt.Errorf("%s: %w", path, err)
			}
		}
		if t, ok := spec["tags"].([]any); ok {
			for _, tag := range t {
				tm, ok := tag.(map[string]any)
				if !ok {
					continue
				}
				name, _ := tm["name"].(string)
				if name == "" {
					continue
				}
				tagsByName[name] = tm
			}
		}
	}

	if len(tagsByName) > 0 {
		tagNames := make([]string, 0, len(tagsByName))
		for n := range tagsByName {
			tagNames = append(tagNames, n)
		}
		sort.Strings(tagNames)
		merged["tags"] = func() []any {
			out := make([]any, 0, len(tagNames))
			for _, n := range tagNames {
				out = append(out, tagsByName[n])
			}
			return out
		}()
	}

	out, err := yaml.Marshal(merged)
	if err != nil {
		return fmt.Errorf("marshal: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		return fmt.Errorf("mkdir: %w", err)
	}
	if err := os.WriteFile(outputPath, out, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", outputPath, err)
	}

	fmt.Printf("merge-openapi: %d module spec(s) → %s\n", len(matches), outputPath)
	return nil
}

func baseSpec() map[string]any {
	return map[string]any{
		"openapi": "3.0.3",
		"info": map[string]any{
			"title":       "GoAuth API",
			"description": "Merged OpenAPI spec for the GoAuth authentication library. Generated by clients/ts/scripts/merge-openapi.go — do not edit by hand.",
			"version":     "0.0.0",
		},
		"servers": []any{
			map[string]any{"url": "{baseUrl}", "description": "Configured BasePath", "variables": map[string]any{
				"baseUrl": map[string]any{"default": "/auth", "description": "Value of config.BasePath"},
			}},
		},
		"paths":      map[string]any{},
		"components": map[string]any{"schemas": map[string]any{}, "securitySchemes": map[string]any{"cookieAuth": map[string]any{"type": "apiKey", "in": "cookie", "name": "goauth_access_session"}, "bearerAuth": map[string]any{"type": "http", "scheme": "bearer", "bearerFormat": "JWT"}}},
	}
}

// mergeComponents merges each sub-key (schemas, securitySchemes, ...) from src into dst.
// Later modules may not overwrite an existing schema with a different shape;
// we detect conflicts so the caller knows to dedupe at the source.
func mergeComponents(dst, src map[string]any) error {
	for key, val := range src {
		srcMap, ok := val.(map[string]any)
		if !ok {
			continue
		}
		dstMap, ok := dst[key].(map[string]any)
		if !ok {
			dstMap = map[string]any{}
			dst[key] = dstMap
		}
		for k, v := range srcMap {
			if previous, exists := dstMap[k]; exists && !reflect.DeepEqual(previous, v) {
				return fmt.Errorf("conflicting component %s/%s", key, k)
			}
			dstMap[k] = v
		}
	}
	return nil
}
